import { randomBytes } from 'node:crypto';

import {
  BACKEND_SERVICE_NAMES,
  SERVICE_DEFAULT_PORTS,
  type BackendServiceName,
} from '@cve/contracts';

/** Values starting with this marker in `.env.example` are secrets to generate. */
export const SECRET_PLACEHOLDER = 'change-me';

export function generateSecret(): string {
  return randomBytes(24).toString('hex');
}

/** Replaces every `KEY=change-me…` line of the template with a fresh random secret. */
export function fillSecrets(template: string, secret: () => string = generateSecret): string {
  return template
    .split('\n')
    .map((line) => {
      const match = /^([A-Z][A-Z0-9_]*)=(.*)$/.exec(line);
      if (!match?.[2]?.startsWith(SECRET_PLACEHOLDER)) return line;
      return `${match[1] ?? ''}=${secret()}`;
    })
    .join('\n');
}

/** Parses simple `KEY=value` dotenv content (no quoting or interpolation). */
export function parseEnvFile(content: string): Map<string, string> {
  const values = new Map<string, string>();
  for (const line of content.split('\n')) {
    const match = /^([A-Z][A-Z0-9_]*)=(.*)$/.exec(line.trim());
    if (match?.[1] !== undefined) values.set(match[1], match[2] ?? '');
  }
  return values;
}

/** Host ports published by `compose.dev.yaml` (127.0.0.1 only). */
export const DEV_HOST_PORTS = {
  postgres: 5432,
  redis: 6379,
  rabbitmq: 5672,
  minio: 9000,
  opensearch: 9200,
  keycloak: 8180,
} as const;

const OBJECT_STORAGE_SERVICES: readonly BackendServiceName[] = [
  'download-service',
  'poc-service',
  'reporting-service',
];

function snake(service: BackendServiceName): string {
  return service.toUpperCase().replaceAll('-', '_');
}

function required(values: Map<string, string>, key: string): string {
  const value = values.get(key);
  if (value === undefined || value === '' || value.startsWith(SECRET_PLACEHOLDER)) {
    throw new Error(`${key} is missing or still a placeholder in .env`);
  }
  return encodeURIComponent(value);
}

/**
 * Builds the per-application `.env` files used by `pnpm dev`, pointing at the infrastructure
 * ports published by `compose.dev.yaml`. Each service only receives its own credentials.
 */
export function renderDevEnvFiles(values: Map<string, string>): Record<string, string> {
  const files: Record<string, string> = {};
  const header = '# Generated by `pnpm env:generate` for local development. Do not commit.\n';

  for (const service of BACKEND_SERVICE_NAMES) {
    const prefix = snake(service);
    const database = service.replaceAll('-', '_');
    const lines = [
      `PORT=${SERVICE_DEFAULT_PORTS[service]}`,
      `DATABASE_URL=postgresql://${database}:${required(values, `${prefix}_DB_PASSWORD`)}@localhost:${DEV_HOST_PORTS.postgres}/${database}`,
      `REDIS_URL=redis://${service}:${required(values, `${prefix}_REDIS_PASSWORD`)}@localhost:${DEV_HOST_PORTS.redis}`,
      `RABBITMQ_URL=amqp://${service}:${required(values, `${prefix}_RABBITMQ_PASSWORD`)}@localhost:${DEV_HOST_PORTS.rabbitmq}/cve`,
    ];
    if (OBJECT_STORAGE_SERVICES.includes(service)) {
      lines.push(
        `S3_ENDPOINT=http://localhost:${DEV_HOST_PORTS.minio}`,
        `S3_ACCESS_KEY_ID=${service}`,
        `S3_SECRET_ACCESS_KEY=${required(values, `${prefix}_MINIO_SECRET_KEY`)}`,
      );
    }
    if (service === 'cve-service') {
      lines.push(
        `OPENSEARCH_URL=https://localhost:${DEV_HOST_PORTS.opensearch}`,
        'OPENSEARCH_USERNAME=cve-service',
        `OPENSEARCH_PASSWORD=${required(values, 'CVE_SERVICE_OPENSEARCH_PASSWORD')}`,
        'OPENSEARCH_CA_FILE=../../.certs/platform-ca.pem',
        `KEYCLOAK_URL=http://localhost:${DEV_HOST_PORTS.keycloak}/auth`,
        `KEYCLOAK_PUBLIC_URL=http://localhost:${DEV_HOST_PORTS.keycloak}/auth`,
      );
    }
    if (service === 'intelligence-service') {
      lines.push(
        `KEYCLOAK_URL=http://localhost:${DEV_HOST_PORTS.keycloak}/auth`,
        `KEYCLOAK_PUBLIC_URL=http://localhost:${DEV_HOST_PORTS.keycloak}/auth`,
      );
      // Optional source credentials are copied only when set.
      for (const key of ['NVD_API_KEY', 'GITHUB_TOKEN']) {
        const value = values.get(key);
        if (value !== undefined && value !== '') lines.push(`${key}=${value}`);
      }
    }
    if (service === 'identity-service') {
      lines.push(
        `KEYCLOAK_URL=http://localhost:${DEV_HOST_PORTS.keycloak}/auth`,
        `KEYCLOAK_PUBLIC_URL=http://localhost:${DEV_HOST_PORTS.keycloak}/auth`,
        `KEYCLOAK_ADMIN_CLIENT_SECRET=${required(values, 'KEYCLOAK_IDENTITY_SERVICE_CLIENT_SECRET')}`,
        'ACCOUNT_REDIRECT_URI=http://localhost:3000/settings',
      );
    }
    files[`services/${service}/.env`] = `${header}${lines.join('\n')}\n`;
  }

  files['apps/api-gateway/.env'] =
    header +
    [
      ...BACKEND_SERVICE_NAMES.map(
        (service) => `${snake(service)}_URL=http://localhost:${SERVICE_DEFAULT_PORTS[service]}`,
      ),
      // compose.dev.yaml sets KC_HOSTNAME to this address, so it is also the token issuer.
      `KEYCLOAK_URL=http://localhost:${DEV_HOST_PORTS.keycloak}/auth`,
      `KEYCLOAK_PUBLIC_URL=http://localhost:${DEV_HOST_PORTS.keycloak}/auth`,
      `KEYCLOAK_INTROSPECTION_CLIENT_SECRET=${required(values, 'KEYCLOAK_API_CLIENT_SECRET')}`,
    ].join('\n') +
    '\n';
  return files;
}
